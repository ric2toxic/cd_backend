		if (!empty($this->request->post['telephone']) && $this->model_account_customer->getTotalCustomersByTelephone($this->request->post['telephone'])) {
			$this->error['telephone'] = $this->language->get('error_exists_phone');
		}
		return !$this->error;
	}

